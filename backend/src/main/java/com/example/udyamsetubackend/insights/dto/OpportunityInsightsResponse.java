package com.example.udyamsetubackend.insights.dto;

import com.example.udyamsetubackend.enquiry.enums.EnquiryStatus;
import com.example.udyamsetubackend.insights.enums.InsightPeriod;
import com.example.udyamsetubackend.insights.enums.OpportunityCategory;
import com.example.udyamsetubackend.insights.enums.OpportunityType;
import com.example.udyamsetubackend.insights.enums.ServiceSource;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;
import java.util.Map;

/**
 * Rule-based recommendations for one reporting period, most significant first. Each recommendation states the
 * counts behind it, so it can be checked. Nothing here is generated by a language model.
 *
 * @param period            reporting period requested
 * @param from              first day of the window
 * @param to                last day of the window (inclusive)
 * @param totalEnquiries    enquiries in the window (the base for shares)
 * @param opportunities     recommendations, at most {@code thresholds.maxOpportunities}
 * @param notes             explanations of suppressed or limited results
 * @param thresholds        the thresholds applied
 */
public record OpportunityInsightsResponse(
        InsightPeriod period,
        LocalDate from,
        LocalDate to,
        long totalEnquiries,
        List<Opportunity> opportunities,
        List<String> notes,
        Thresholds thresholds
) {

    /**
     * One recommendation.
     *
     * @param type                 kind of opportunity
     * @param category             business area, derived from the type
     * @param title                short headline
     * @param explanation          plain-language reason, with the counts
     * @param serviceKey           {@code SERVICE:<id>} or {@code TEXT:<normalised>}
     * @param serviceName          display name
     * @param serviceSource        CATALOGUE or FREE_TEXT
     * @param serviceActive        catalogue active flag; null for free text
     * @param supportingEnquiryCount enquiries the recommendation is based on (for example UNFULFILLED count)
     * @param recentCount          enquiries in the recent half of the period
     * @param previousCount        enquiries in the earlier half of the period
     * @param statusCounts         enquiries per status for this service (every status present)
     * @param periodFrom           first day of the evidence window
     * @param periodTo             last day of the evidence window
     * @param suggestedAction      what the business could do about it
     */
    public record Opportunity(
            OpportunityType type,
            OpportunityCategory category,
            String title,
            String explanation,
            String serviceKey,
            String serviceName,
            ServiceSource serviceSource,
            Boolean serviceActive,
            long supportingEnquiryCount,
            long recentCount,
            long previousCount,
            Map<EnquiryStatus, Long> statusCounts,
            LocalDate periodFrom,
            LocalDate periodTo,
            String suggestedAction
    ) {
    }

    /** The thresholds used for this response. */
    public record Thresholds(
            int lastDaysWindow,
            int minSampleSize,
            int minRepeatedUnfulfilled,
            int minFrequentRequests,
            BigDecimal minFrequentShare,
            BigDecimal highLostRate,
            int minRecentForGrowth,
            int minPreviousForGrowth,
            BigDecimal trendChangeRatio,
            int maxOpportunities
    ) {
    }
}
